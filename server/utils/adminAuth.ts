// Authentication for the submissions view.
//
// This guards prescription data on a public, internet-facing box, so:
//
//   - It fails CLOSED. With no password configured the area returns 503 and
//     shows nothing. An unconfigured deployment must never be an open one.
//   - It is independent of any Caddy basic auth in front of staging. Removing
//     that at cutover must not expose anything.
//   - It guards the API routes, not just the page. The page is only a renderer;
//     the listing and download endpoints are what hold the data.
//
// scrypt for the password, HMAC-signed cookie for the session, both from
// node:crypto. No new dependencies.

import { createHmac, randomBytes, scryptSync, timingSafeEqual } from "node:crypto";
import type { H3Event } from "h3";

export const SESSION_COOKIE = "gp_admin";
export const SESSION_HOURS = 8;
const SCRYPT_KEYLEN = 64;

// ---------------------------------------------------------------------------
// Password
// ---------------------------------------------------------------------------

/** Format: `scrypt$<saltHex>$<hashHex>`. Generated by scripts/hash-admin-password.mjs. */
export function hashPassword(password: string): string {
  const salt = randomBytes(16);
  return `scrypt$${salt.toString("hex")}$${scryptSync(password, salt, SCRYPT_KEYLEN).toString("hex")}`;
}

export function verifyPassword(password: string, stored: string): boolean {
  const parts = stored.split("$");
  if (parts.length !== 3 || parts[0] !== "scrypt") return false;

  let salt: Buffer;
  let expected: Buffer;
  try {
    salt = Buffer.from(parts[1], "hex");
    expected = Buffer.from(parts[2], "hex");
  } catch {
    return false;
  }
  if (salt.length === 0 || expected.length !== SCRYPT_KEYLEN) return false;

  return timingSafeEqual(scryptSync(password, salt, SCRYPT_KEYLEN), expected);
}

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

function sessionSecret(): string | undefined {
  // Falls back to the password hash, so setting only the password still yields
  // signed sessions rather than silently unsigned ones.
  return process.env.ADMIN_SESSION_SECRET || process.env.ADMIN_PASSWORD_HASH;
}

export function adminConfigured(): boolean {
  return Boolean(process.env.ADMIN_PASSWORD_HASH && sessionSecret());
}

// ---------------------------------------------------------------------------
// Session token: `<expiryMs>.<hmac>`
// ---------------------------------------------------------------------------

function sign(payload: string): string {
  return createHmac("sha256", sessionSecret()!).update(payload).digest("hex");
}

export function issueToken(now = Date.now()): string {
  const payload = String(now + SESSION_HOURS * 3600_000);
  return `${payload}.${sign(payload)}`;
}

export function tokenValid(token: string | undefined, now = Date.now()): boolean {
  if (!token || !adminConfigured()) return false;

  const dot = token.lastIndexOf(".");
  if (dot <= 0) return false;

  const payload = token.slice(0, dot);
  let provided: Buffer;
  try {
    provided = Buffer.from(token.slice(dot + 1), "hex");
  } catch {
    return false;
  }
  const expected = Buffer.from(sign(payload), "hex");
  if (provided.length !== expected.length) return false;
  if (!timingSafeEqual(provided, expected)) return false;

  const expires = Number(payload);
  return Number.isFinite(expires) && expires > now;
}

// ---------------------------------------------------------------------------
// Cookies and the route guard
// ---------------------------------------------------------------------------

export function setSessionCookie(event: H3Event, token: string): void {
  setCookie(event, SESSION_COOKIE, token, {
    httpOnly: true,
    sameSite: "strict",
    secure: process.env.NODE_ENV === "production",
    path: "/",
    maxAge: SESSION_HOURS * 3600,
  });
}

export function clearSessionCookie(event: H3Event): void {
  deleteCookie(event, SESSION_COOKIE, { path: "/" });
}

/** Call first in every admin route, including file downloads. */
export function requireAdmin(event: H3Event): void {
  if (!adminConfigured()) {
    console.warn(
      "[admin] blocked: ADMIN_PASSWORD_HASH is not set, so the submissions area is disabled",
    );
    throw createError({
      statusCode: 503,
      // Deliberately vague: the detail goes to the server log, not to whoever
      // happens to be asking.
      statusMessage: "This area is not available.",
    });
  }
  if (!tokenValid(getCookie(event, SESSION_COOKIE))) {
    throw createError({ statusCode: 401, statusMessage: "Sign in to continue." });
  }
  // Patient data must not be cached by the browser or anything in between.
  setResponseHeader(event, "Cache-Control", "no-store");
}
