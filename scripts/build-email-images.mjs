// Regenerates server/utils/receiptImages.ts, the two pictures inlined in the
// patient's receipt email:
//
//   LOGO    assets/images/logostyles/logo-wide.svg, rendered to a 2x PNG.
//           Email clients do not show SVG, so the site's logo is rasterized.
//   SPROUT  assets/images/email/sprout@2x.png, the same file the dashboard's
//           "ready" email uses (shift-dashboard server/src/mail/assets/).
//
// Run after changing either source:
//
//   node scripts/build-email-images.mjs
//
// Needs Playwright's Chromium (npx playwright install chromium).

import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "playwright";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root));

async function renderSvg(path, width, height, scale) {
  const svg = read(path).toString("base64");
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ deviceScaleFactor: scale });
    await page.setContent(
      `<html><body style="margin:0;background:transparent"><img id="i" src="data:image/svg+xml;base64,${svg}" style="display:block;width:${width}px;height:${height}px"></body></html>`,
    );
    return await page.locator("#i").screenshot({ omitBackground: true });
  } finally {
    await browser.close();
  }
}

const logo = await renderSvg("assets/images/logostyles/logo-wide.svg", 172, 50, 2);
const sprout = read("assets/images/email/sprout@2x.png");

writeFileSync(
  new URL("server/utils/receiptImages.ts", root),
  `// Generated by scripts/build-email-images.mjs. Do not edit by hand.
//
// The pictures in the patient's receipt email, inlined (cid:) so the email needs
// no image hosting and shows them even where remote images are blocked.

/** assets/images/logostyles/logo-wide.svg as a 344x100 PNG, shown at 172x50 */
export const LOGO_PNG_BASE64 =
  "${logo.toString("base64")}";

/** assets/images/email/sprout@2x.png, 112x128, shown at 56x64 */
export const SPROUT_PNG_BASE64 =
  "${sprout.toString("base64")}";
`,
);
console.log(`receiptImages.ts written (logo ${logo.length} bytes, sprout ${sprout.length} bytes)`);
